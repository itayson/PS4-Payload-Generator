import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
const candidate = await readFile(new URL('../builds/seek-smart-transport-v0.1.js', import.meta.url), 'utf8');
const worker = (await import('data:text/javascript;charset=utf-8,' + encodeURIComponent(candidate))).default;
test('integrated legacy POST, HEAD, Range, proxy and guarded DIRECT', async () => {
const prefix='https://lab.test';
const originHost='rootz-files.'+'a'.repeat(32)+'.r2.cloudflarestorage.com';
const stamp=new Date().toISOString().replace(/[-:]/g,'').replace(/\.\d+Z$/, 'Z');
const signed='https://'+originHost+'/demo.pkg?X-Amz-Algorithm=AWS4-HMAC-SHA256&X-Amz-Date='+stamp+'&X-Amz-Expires=86400&X-Amz-Signature=fake123';
const total='5368709120';
const key='FAKE_UNIT_TEST_KEY';
const hits=[];
let originMode='normal';
globalThis.fetch=async(url,options={})=>{
  const range=new Headers(options.headers).get('Range')||'';
  hits.push({method:options.method,range});
  if(originMode==='html')return new Response('<htm',{status:206,headers:{'Content-Type':'text/html','Content-Range':'bytes 0-3/'+total,'Content-Length':'4'}});
  const match=/^bytes=(\d+)-(\d*)$/.exec(range);
  if(!match)throw Error('mock origin rejects unbounded streaming');
  const start=Number(match[1]);
  const end=match[2] ? Number(match[2]) : start+3;
  if(start >= Number(total))return new Response(null,{status:416,headers:{'Content-Range':'bytes */'+total}});
  const size=end-start+1;
  if(size>4)throw Error('mock range too long');
  const bytes=start===0?new Uint8Array([127,67,78,84]):new Uint8Array([1,2,3,4].slice(0,size));
  return new Response(bytes,{status:206,headers:{'Content-Type':'application/octet-stream','Content-Range':'bytes '+start+'-'+end+'/'+total,'Content-Length':String(size),'Accept-Ranges':'bytes'}});
};
const kv=new Map();
const env={ROUTES:{get:async k=>kv.get(k)||null,put:async(k,v)=>{kv.set(k,v)}},ROUTE_API_KEY:key,DISABLE_PUBLIC_FALLBACK:'true',SMART_DIRECT_ENABLED:'false',SMART_BGFT_REDIRECT_VERIFIED:'false'};
const checks=[];
const health=await worker.fetch(new Request(prefix+'/health'),env);
assert.equal(health.status,200);
checks.push('health 200');
const unauthorized=await worker.fetch(new Request(prefix+'/api/routes',{method:'POST',body:signed}),env);
assert.equal(unauthorized.status,401);
checks.push('POST without key 401');
const made=await worker.fetch(new Request(prefix+'/api/routes',{method:'POST',headers:{'X-Api-Key':key},body:signed}),env);
assert.equal(made.status,200,await made.clone().text());
const route=(await made.text()).trim();
assert.match(route,/^https:\/\/[^/]+\/d\/[a-f0-9]{32}\.pkg$/);
checks.push('legacy route POST text/plain short .pkg');
const initial=await worker.fetch(new Request(route,{headers:{Range:'bytes=0-3'}}),env);
assert.equal(initial.status,206,await initial.clone().text());
assert.equal(initial.headers.get('content-range'),'bytes 0-3/'+total);
assert.deepEqual(Array.from(new Uint8Array(await initial.arrayBuffer())),[127,67,78,84]);
checks.push('PROXY 206 initial bytes');
const resumed=await worker.fetch(new Request(route,{headers:{Range:'bytes=4096-4099'}}),env);
assert.equal(resumed.status,206,await resumed.clone().text());
assert.equal(resumed.headers.get('content-range'),'bytes 4096-4099/'+total);
assert.deepEqual(Array.from(new Uint8Array(await resumed.arrayBuffer())),[1,2,3,4]);
checks.push('PROXY 206 non-zero range');
const h=await worker.fetch(new Request(route,{method:'HEAD'}),env);
assert.equal(h.status,200);
assert.equal(h.headers.get('content-length'),total);
checks.push('HEAD size for BGFT');
const nofallback=await worker.fetch(new Request(prefix+'/r2.pkg'),env);
assert.equal(nofallback.status,404);
checks.push('public fallback disabled');
const error=await worker.fetch(new Request(route,{headers:{Range:'bytes=999999999999-'}}),env);
assert.equal(error.status,416);
assert.equal(error.headers.get('content-range'),'bytes */'+total);
checks.push('416 preserves total');
originMode='html';
const html=await worker.fetch(new Request(route,{headers:{Range:'bytes=0-3'}}),env);
assert.equal(html.status,502);
checks.push('reject HTML error masquerading as PKG');
originMode='normal';
env.SMART_DIRECT_ENABLED='true';env.SMART_BGFT_REDIRECT_VERIFIED='true';
const block=await worker.fetch(new Request(route,{headers:{Range:'bytes=0-3'}}),env);
assert.equal(block.status,206);
checks.push('DIRECT blocked without provider opt-in');
env.SMART_DIRECT_PROVIDERS='r2';
const direct=await worker.fetch(new Request(route,{headers:{Range:'bytes=0-3'}}),env);
assert.equal(direct.status,307,await direct.clone().text());
assert.equal(direct.headers.get('location'),signed);
assert.equal(direct.headers.get('x-tayson-transport'),'DIRECT');
checks.push('DIRECT 307 only with provider-scoped opt-in');
console.log('INTEGRATED_TEST_RESULTS='+JSON.stringify({passed:checks.length,checks,upstreamProbes:hits.length,storedRoutes:kv.size}));


});
